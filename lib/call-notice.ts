import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';

export type NoticeInput = {
  fundName: string;
  callNumber: number;
  callDate: string; // YYYY-MM-DD
  dueDate: string;
  purpose: string;
  investorName: string;
  commitment: number;
  unfundedBefore: number;
  amount: number;
  totalCall: number;
  verifyPhone?: string | null;
};

const usd = (n: number) => n.toLocaleString('en-US', { style: 'currency', currency: 'USD' });
const date = (d: string) => new Date(d + 'T12:00:00Z').toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric', timeZone: 'UTC' });

/** One-page capital call notice for one investor. Deliberately contains no bank details. */
export async function buildCallNotice(n: NoticeInput) {
  const doc = await PDFDocument.create();
  const page = doc.addPage([612, 792]);
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const ink = rgb(0.08, 0.13, 0.24);
  const grey = rgb(0.38, 0.4, 0.46);
  const red = rgb(0.7, 0.15, 0.12);
  const L = 60, W = 492;
  let y = 730;
  const t = (s: string, x: number, size = 10, f = font, c = ink) => page.drawText(s.replace(/[^\x20-\x7E]/g, ' '), { x, y, size, font: f, color: c });
  const wrap = (s: string, size: number, f = font, width = W) => {
    const out: string[] = []; let cur = '';
    for (const w of s.replace(/[^\x20-\x7E]/g, ' ').split(/\s+/)) {
      const nx = cur ? `${cur} ${w}` : w;
      if (f.widthOfTextAtSize(nx, size) > width) { out.push(cur); cur = w; } else cur = nx;
    }
    if (cur) out.push(cur);
    return out;
  };

  t(n.fundName, L, 11, bold, grey); y -= 26;
  t(`Capital Call Notice No. ${n.callNumber}`, L, 20, bold); y -= 20;
  t(`Date of notice: ${date(n.callDate)}`, L, 10, font, grey); y -= 34;

  t(`To: ${n.investorName}`, L, 11, bold); y -= 22;
  for (const ln of wrap(`Pursuant to the fund's governing documents, the General Partner is calling capital from the Limited Partners pro rata to their unfunded Capital Commitments. Your share is set out below.`, 10)) { t(ln, L); y -= 14; }
  y -= 10;

  const rows: [string, string, boolean?][] = [
    ['Your Capital Commitment', usd(n.commitment)],
    ['Unfunded before this call', usd(n.unfundedBefore)],
    ['Amount due under this call', usd(n.amount), true],
    ['Unfunded after this call', usd(n.unfundedBefore - n.amount)],
    ['Due date (funds received by)', date(n.dueDate), true],
    ['Total called from all investors', usd(n.totalCall)],
  ];
  for (const [k, v, strong] of rows) {
    page.drawLine({ start: { x: L, y: y + 14 }, end: { x: L + W, y: y + 14 }, thickness: 0.4, color: rgb(0.85, 0.86, 0.9) });
    t(k, L, 10, font, grey);
    page.drawText(v, { x: L + W - (strong ? bold : font).widthOfTextAtSize(v, strong ? 12 : 10), y, size: strong ? 12 : 10, font: strong ? bold : font, color: ink });
    y -= 22;
  }
  y -= 10;
  t('Purpose of this call', L, 10, bold); y -= 15;
  for (const ln of wrap(n.purpose, 10)) { t(ln, L); y -= 14; }
  y -= 16;

  t('How to fund', L, 10, bold); y -= 15;
  for (const ln of wrap('Wire instructions are shown in your investor portal (Funding instructions). Please include your name and "Capital Call ' + n.callNumber + '" in the wire reference.', 10)) { t(ln, L); y -= 14; }
  y -= 12;

  const warn = wrap(`WIRE FRAUD WARNING: We will never send or change wiring instructions by email. Before sending funds, call ${n.verifyPhone || 'the fund manager at a number you already know'} to confirm the instructions by voice. If anything looks different, stop and call us.`, 9.5, bold, W - 18);
  const h = warn.length * 13 + 14;
  page.drawRectangle({ x: L, y: y - h + 10, width: W, height: h, borderColor: red, borderWidth: 1, color: rgb(0.99, 0.95, 0.94) });
  y -= 4;
  for (const ln of warn) { page.drawText(ln, { x: L + 8, y, size: 9.5, font: bold, color: red }); y -= 13; }
  y -= 22;
  for (const ln of wrap('Failure to fund by the due date may have consequences under the default provisions of the fund\'s governing documents. Questions: contact the fund manager. This notice was generated by VCG FundOS.', 8.5)) { t(ln, L, 8.5, font, grey); y -= 11; }

  doc.setTitle(`Capital Call Notice No. ${n.callNumber}: ${n.investorName}`);
  doc.setProducer('VCG FundOS');
  return doc.save();
}
